def box(title, body, tint=AMBER_L, edge=AMBER):
    inner = []
    if title:
        inner.append(Paragraph('<font color="%s"><b>%s</b></font>' % (edge.hexval(), title), S['note']))
    for line in body:
        inner.append(Paragraph(line, S['note']))
    t = Table([[inner]], colWidths=[165*mm])
    t.setStyle(TableStyle([
        ('BACKGROUND', (0,0), (-1,-1), tint),
        ('BOX',        (0,0), (-1,-1), 0.8, edge),
        ('LEFTPADDING',(0,0), (-1,-1), 9), ('RIGHTPADDING',(0,0), (-1,-1), 9),
        ('TOPPADDING', (0,0), (-1,-1), 7), ('BOTTOMPADDING',(0,0),(-1,-1), 7),
    ]))
    return t

def table(rows, widths, header=True):
    data = []
    for r_i, row in enumerate(rows):
        data.append([Paragraph(c, S['cellb'] if (header and r_i == 0) else S['cell']) for c in row])
    t = Table(data, colWidths=widths, repeatRows=1 if header else 0)
    style = [
        ('VALIGN',       (0,0), (-1,-1), 'TOP'),
        ('GRID',         (0,0), (-1,-1), 0.5, LINE),
        ('LEFTPADDING',  (0,0), (-1,-1), 7), ('RIGHTPADDING', (0,0), (-1,-1), 7),
        ('TOPPADDING',   (0,0), (-1,-1), 5), ('BOTTOMPADDING',(0,0), (-1,-1), 5),
    ]
    if header:
        style += [('BACKGROUND', (0,0), (-1,0), GREEN_L),
                  ('LINEBELOW',  (0,0), (-1,0), 0.9, GREEN)]
    t.setStyle(TableStyle(style))
    return t

def steps(items):
    rows = []
    for i, (head, text) in enumerate(items, 1):
        num = Paragraph('<font color="%s"><b>%d</b></font>' % (GREEN.hexval(), i), S['cellb'])
        body = [Paragraph('<b>%s</b>' % head, S['cell'])]
        if text:
            body.append(Spacer(1, 2))
            body.append(Paragraph(text, S['cell']))
        rows.append([num, body])
    t = Table(rows, colWidths=[9*mm, 156*mm])
    t.setStyle(TableStyle([
        ('VALIGN',       (0,0), (-1,-1), 'TOP'),
        ('LEFTPADDING',  (0,0), (0,-1), 0),
        ('LEFTPADDING',  (1,0), (1,-1), 4),
        ('TOPPADDING',   (0,0), (-1,-1), 4), ('BOTTOMPADDING',(0,0), (-1,-1), 4),
        ('LINEBELOW',    (0,0), (-1,-2), 0.4, colors.HexColor('#e5e7eb')),
    ]))
    return t

